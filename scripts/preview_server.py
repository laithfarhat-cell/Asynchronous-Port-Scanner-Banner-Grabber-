def _demo_findings() -> tuple[list[dict[str, Any]], dict[str, Any]]:
    source = active_json()
    if source is None:
        return [], {}
    try:
        payload = json.loads(source.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return [], {}
    findings: list[dict[str, Any]] = []
    for host in payload.get("hosts", []):
        for port in host.get("ports", []):
            findings.append({"host": host, "port": port})
    return findings, payload.get("summary", {})


def _cli_help() -> str:
    try:
        completed = subprocess.run(
            [sys.executable, str(ROOT / "main.py"), "--help"],
            capture_output=True,
            text=True,
            timeout=30,
            cwd=str(ROOT),
        )
        text = completed.stdout or completed.stderr
    except (OSError, subprocess.SubprocessError) as exc:  # pragma: no cover
        text = f"could not render --help: {exc}"
    return text.replace("\x1b", "")


def render_index() -> str:
    findings, summary = _demo_findings()
    rows: list[str] = []
    for item in findings:
        host, port = item["host"], item["port"]
        tls = port.get("tls") or {}
        tls_bits = []
        if tls.get("subject_cn"):
            tls_bits.append(f"CN={html.escape(tls['subject_cn'])}")
        if tls.get("issuer_cn"):
            tls_bits.append(f"issuer={html.escape(tls['issuer_cn'])}")
        if tls.get("not_after"):
            tls_bits.append(f"expires {html.escape(tls['not_after'][:10])}")
        if tls.get("tls_version"):
            tls_bits.append(html.escape(tls["tls_version"]))
        banner = html.escape(" ".join(str(port.get("banner") or "").split())[:150])
        service = port.get("product") or port.get("service") or "unknown"
        if port.get("version"):
            service = f"{service}/{port['version']}"
        rows.append(
            "<tr>"
            f'<td class="mono">{html.escape(host.get("ip", ""))}</td>'
            f'<td class="mono">{html.escape(str(host.get("hostname") or "-"))}</td>'
            f'<td class="mono">{port.get("port")}</td>'
            f'<td><span class="badge">{html.escape(service)}</span></td>'
            f'<td class="mono">{banner}'
            + (f'<div style="color:var(--muted)">{html.escape(" · ".join(tls_bits))}</div>' if tls_bits else "")
            + "</td>"
            f'<td class="mono">{port.get("latency_ms") if port.get("latency_ms") is not None else "-"}</td>'
            "</tr>"
        )
    if not rows:
        rows.append('<tr><td colspan="6">No demo reports yet — run <code>python3 scripts/demo_lab.py</code>.</td></tr>')

    signatures = SignatureDatabase.load()
    sig_rows = []
    for rule in signatures.rules:
        sig_rows.append(
            "<tr>"
            f'<td class="mono">{html.escape(rule["id"])}</td>'
            f'<td class="mono">{html.escape(rule["service"] or "generic")}</td>'
            f'<td class="mono" style="color:#8aa0b4">{html.escape(rule["pattern"] or "")}</td>'
            "</tr>"
        )

    return INDEX.format(
        open_ports=summary.get("open_ports", len(findings)),
        hosts_open=summary.get("hosts_with_open_ports", 0),
        rules=len(signatures),
        presets=f"{len(load_top_ports(100))}/{len(load_top_ports(1000))}",
        rows="\n".join(rows),
        sig_rows="\n".join(sig_rows),
        help_text=html.escape(_cli_help()),
    )


class PreviewHandler(BaseHTTPRequestHandler):
    server_version = "asynscan-preview/1.0"
    protocol_version = "HTTP/1.1"

    def _send(self, body: bytes, status: int = 200, content_type: str = "text/html; charset=utf-8") -> None:
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def _json(self, payload: Any, status: int = 200) -> None:
        self._send(json.dumps(payload, indent=2).encode() + b"\n", status, "application/json; charset=utf-8")

    def do_HEAD(self) -> None:  # noqa: N802 - http.server API
        self.do_GET()

    def do_GET(self) -> None:  # noqa: N802 - http.server API
        path = urlparse(self.path).path.rstrip("/") or "/"
        try:
            if path in ("/", "/index.html"):
                self._send(render_index().encode())
            elif path == "/healthz":
                report, payload = active_report(), active_json()
                self._json(
                    {
                        "status": "ok",
                        "report": report.relative_to(ROOT).as_posix() if report else None,
                        "data": payload.relative_to(ROOT).as_posix() if payload else None,
                        "generated": report is not None and report.parent.name == "reports",
                    }
                )
            elif path == "/reports/demo":
                report = active_report()
                if report is not None:
                    self._send(report.read_bytes())
                else:
                    self._send(b"no demo report yet: run python3 scripts/demo_lab.py\n", 404, "text/plain; charset=utf-8")
            elif path == "/reports/demo.json":
                payload = active_json()
                if payload is not None:
                    self._send(payload.read_bytes(), 200, "application/json; charset=utf-8")
                else:
                    self._json({"error": "run python3 scripts/demo_lab.py first"}, 404)
            elif path == "/reports/demo.csv":
                csv_path = ROOT / "reports" / "demo.csv"
                if csv_path.is_file():
                    self._send(csv_path.read_bytes(), 200, "text/csv; charset=utf-8")
                else:
                    self._send(b"", 404, "text/plain; charset=utf-8")
            elif path == "/api/signatures":
                db = SignatureDatabase.load()
                self._json(
                    {
                        "count": len(db),
                        "rules": [
                            {"id": r["id"], "service": r["service"], "pattern": r["pattern"]}
                            for r in db.rules
                        ],
                    }
                )
            elif path == "/api/ports":
                self._json({"top_100": load_top_ports(100), "top_1000": load_top_ports(1000)})
            elif path == "/api/help":
                self._json({"usage": _cli_help()})
            else:
                self._json({"error": "not found", "path": path}, 404)
        except BrokenPipeError:  # pragma: no cover - client vanished
            pass
        except Exception as exc:  # pragma: no cover - keep the preview alive
            self._json({"error": type(exc).__name__, "detail": str(exc)}, 500)

    def log_message(self, fmt: str, *args: Any) -> None:  # keep the console readable
        sys.stderr.write(f"[preview] {self.address_string()} {fmt % args}\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host", default="0.0.0.0", help="bind address (default 0.0.0.0 for previews)")
    parser.add_argument("--port", type=int, default=32929, help="bind port (default 32929)")
    args = parser.parse_args()

    server = ThreadingHTTPServer((args.host, args.port), PreviewHandler)
    server.daemon_threads = True
    print(f"asynscan preview console → http://{args.host}:{args.port}", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nstopping", flush=True)
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
