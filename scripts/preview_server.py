def active_report() -> Path | None:
    """Prefer a freshly generated report, fall back to the shipped sample."""
    for candidate in (DEMO_REPORT, SAMPLE_REPORT):
        if candidate.is_file():
            return candidate
    return None


def active_json() -> Path | None:
    for candidate in (DEMO_JSON, SAMPLE_JSON):
        if candidate.is_file():
            return candidate
    return None

