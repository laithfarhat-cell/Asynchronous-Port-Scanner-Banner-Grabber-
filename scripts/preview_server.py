"""asynscan console — a tiny local preview server for the tool.

This project is a CLI, not a web app, so there is no "dev server" to run. This
script exists so the workspace has something meaningful to preview: it serves a
single-page console that

* shows the demo findings (``reports/demo.json``) as the tool's dark-mode tables,
* lets you inspect the bundled signature database and port presets,
* documents the CLI reference straight from ``asynscan --help``.

Everything is offline and loopback-only: no CDN, no external fonts, no telemetry.

Usage
-----
    python3 scripts/preview_server.py --port 32929 --host 0.0.0.0
"""

